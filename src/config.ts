/**
 * Configuration for the CLI. Keys mirror the VS Code settings (without the `diffLeppard.` prefix),
 * so a config file looks like:
 *
 *   { "baseUrl": "http://gpu-box:8000/v1", "model": "qwen2.5-coder:32b", "apiKey": "…",
 *     "extraBody": { "chat_template_kwargs": { "enable_thinking": false } },
 *     "github": { "reviewEvent": "COMMENT" } }
 *
 * Precedence (lowest → highest): defaults, user config file, repo config file (restricted keys), environment, CLI flags.
 */
import { promises as fs } from 'fs';
import * as os from 'os';
import * as path from 'path';
import { ReviewEventSetting } from './github';
import { JsonMode } from './llm';
import { Severity, SEVERITIES } from './types';

export interface CliSettings {
  provider: 'openai' | 'ollama';
  baseUrl: string;
  model: string;
  apiKey: string;
  temperature: number;
  maxOutputTokens: number;
  jsonMode: JsonMode;
  stream: boolean;
  requestTimeoutSeconds: number;
  concurrency: number;
  ollamaNumCtx: number;
  extraHeaders: Record<string, string>;
  extraBody: Record<string, unknown>;
  maxChunkChars: number;
  contextLines: number;
  includeUntracked: boolean;
  minimumSeverity: Severity;
  excludeGlobs: string[];
  extraInstructions: string;
  instructionsFile: string;
  github: {
    apiUrl: string;
    reviewEvent: ReviewEventSetting;
    suggestionBlocks: boolean;
    /** Append "Review generated by Diff Leppard, running <model>" to posted reviews. */
    attribution: boolean;
  };
  /** `diff-leppard watch`: automatic reviews across all repos you can access (user config only). */
  watch: WatchSettings;
}

export interface WatchSettings {
  /** Minutes between checks in loop mode. */
  intervalMinutes: number;
  /** How to post: a pending draft you submit yourself (default), a comment, or request-changes-if-blocking. */
  event: ReviewEventSetting;
  /** PRs where your review was requested: 'user' = you personally, 'team' = you or a team you're in, 'off'. */
  reviewRequests: 'user' | 'team' | 'off';
  /** Also review PRs you opened. */
  ownPullRequests: boolean;
  /** Extra GitHub search qualifiers for another set of PRs, e.g. "org:acme label:diff-leppard". */
  query: string;
  /** Only these repos (owner/repo or owner/*); empty = all. */
  repos: string[];
  /** Never these repos (owner/repo or owner/*). */
  excludeRepos: string[];
  /** Review again when new commits are pushed (default: once per PR). */
  rereviewOnPush: boolean;
  /** Skip draft PRs. */
  skipDrafts: boolean;
  /** At most this many reviews per check (the rest wait for the next one). */
  maxPerRun: number;
  /** Where reviewed PRs are recorded; empty = $XDG_STATE_HOME/diff-leppard/watch.json. */
  stateFile: string;
}

