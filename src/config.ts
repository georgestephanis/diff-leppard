export const REPO_CONFIG_FILE = '.diff-leppard.json';

export function userConfigPath(env: NodeJS.ProcessEnv = process.env): string {
  if (env.DIFF_LEPPARD_CONFIG) return env.DIFF_LEPPARD_CONFIG;
  const base = env.XDG_CONFIG_HOME || path.join(os.homedir(), '.config');
  return path.join(base, 'diff-leppard', 'config.json');
}

type Json = Record<string, unknown>;

function isObj(v: unknown): v is Json {
  return !!v && typeof v === 'object' && !Array.isArray(v);
}

/** Flatten `diffLeppard.` prefixes and `github.x` dotted keys into the nested settings shape. */
/** Setting groups that nest one level: `github.apiUrl`, `watch.repos`, … */
const NESTED = ['github', 'watch'];

export function normalizeKeys(o: Json): Json {
  const out: Json = {};
  for (let [k, v] of Object.entries(o)) {
    if (v === undefined) continue;
    k = k.replace(/^diffLeppard\./, '');
    const dot = k.indexOf('.');
    const group = dot > 0 ? k.slice(0, dot) : k;
    if (dot > 0 && NESTED.includes(group)) {
      out[group] = { ...((out[group] as Json) ?? {}), [k.slice(dot + 1)]: v };
    } else if (NESTED.includes(k) && isObj(v)) {
      out[k] = { ...((out[k] as Json) ?? {}), ...v };
    } else out[k] = v;
  }
  return out;
}

/** Deep-merge plain objects; arrays and scalars replace. Accepts `diffLeppard.`-prefixed keys too. */
export function merge<T extends Json>(base: T, over: Json): T {
  const out: Json = { ...base };
  for (const [k, v] of Object.entries(normalizeKeys(over))) {
    out[k] = isObj(v) && isObj(out[k]) && k !== 'extraHeaders' && k !== 'extraBody' ? merge(out[k] as Json, v) : v;
  }
  return out as T;
}

/** Parse JSON with comments and trailing commas (like VS Code settings), leaving string contents untouched. */
export function parseJsonc(text: string): unknown {
  // Two string-aware passes: drop comments, then drop commas that precede } or ].
  const scan = (src: string, onCode: (src: string, i: number) => { skip: number; emit: string } | undefined) => {
    let out = '';
    let i = 0;
    while (i < src.length) {
      if (src[i] === '"') {
        let j = i + 1;
        while (j < src.length && src[j] !== '"') j += src[j] === '\\' ? 2 : 1;
        out += src.slice(i, j + 1);
        i = j + 1;
        continue;
      }
      const r = onCode(src, i);
      if (r) {
        out += r.emit;
        i += r.skip;
      } else out += src[i++];
    }
    return out;
  };
  const noComments = scan(text, (src, i) => {
    if (src[i] === '/' && src[i + 1] === '/') {
      const nl = src.indexOf('\n', i);
      return { skip: (nl < 0 ? src.length : nl) - i, emit: '' };
    }
    if (src[i] === '/' && src[i + 1] === '*') {
      const end = src.indexOf('*/', i + 2);
      return { skip: (end < 0 ? src.length : end + 2) - i, emit: ' ' };
    }
    return undefined;
  });
  const noTrailingCommas = scan(noComments, (src, i) => (src[i] === ',' && /^\s*[}\]]/.test(src.slice(i + 1)) ? { skip: 1, emit: '' } : undefined));
  return JSON.parse(noTrailingCommas);
}

export async function readJsonFile(file: string): Promise<Json | undefined> {
  let text: string;
  try {
    text = await fs.readFile(file, 'utf8');
  } catch {
    return undefined;
  }
  try {
    const j = parseJsonc(text);
    if (!isObj(j)) throw new Error('not an object');
    return j;
  } catch (e) {
    throw new Error(`Could not parse ${file}: ${(e as Error).message}`);
  }
}

/**
 * Keys a repository's .diff-leppard.json may set. Anything that decides where requests (and credentials)
 * go, what's sent, or how much load is generated stays under the user's control: a repo, or a PR branch
 * of it, must not be able to redirect your API key / GitHub token or rewrite the request.
 */
export const REPO_CONFIG_KEYS = [
  'model',
  'temperature',
  'maxChunkChars',
  'contextLines',
  'includeUntracked',
  'minimumSeverity',
  'excludeGlobs',
  'extraInstructions',
  'instructionsFile',
] as const;

/** Keep only allowed keys from a repo config; report the rest. */
export function filterRepoConfig(json: Json): { allowed: Json; ignored: string[] } {
  const flat = normalizeKeys(json);
  const allowed: Json = {};
  const ignored: string[] = [];
  for (const [k, v] of Object.entries(flat)) {
    if ((REPO_CONFIG_KEYS as readonly string[]).includes(k)) allowed[k] = v;
    else if (NESTED.includes(k) && isObj(v)) ignored.push(...Object.keys(v).map((g) => `${k}.${g}`));
    else ignored.push(k);
  }
  return { allowed, ignored };
}

const upperSnake = (k: string) => k.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();

/** Aliases kept for the GitHub Action and older docs. */
const ENV_ALIASES: Record<string, string> = { MIN_SEVERITY: 'minimumSeverity', TIMEOUT_SECONDS: 'requestTimeoutSeconds' };

function parseEnvValue(name: string, raw: string, sample: unknown): unknown {
  if (typeof sample === 'number') return Number(raw);
  if (typeof sample === 'boolean') {
    if (/^(1|true|yes|on)$/i.test(raw)) return true;
    if (/^(0|false|no|off)$/i.test(raw)) return false;
    throw new Error(`${name} must be true or false`);
  }
  if (Array.isArray(sample)) {
    if (raw.trim().startsWith('[')) {
      const v = JSON.parse(raw);
      if (!Array.isArray(v)) throw new Error(`${name} must be a JSON array or a comma-separated list`);
      return v;
    }
    return raw.split(',').map((x) => x.trim()).filter(Boolean);
  }
  if (isObj(sample)) {
    let v: unknown;
    try {
      v = JSON.parse(raw);
    } catch {
      throw new Error(`${name} must be a JSON object`);
    }
    if (!isObj(v)) throw new Error(`${name} must be a JSON object`);
    return v;
  }
  return raw;
}

/** Every setting is available as DIFF_LEPPARD_<UPPER_SNAKE_KEY> (github.x as DIFF_LEPPARD_GITHUB_X, watch.x as DIFF_LEPPARD_WATCH_X). */
export function envSettings(env: NodeJS.ProcessEnv): Json {
  const o: Json = {};
  if (env.GH_HOST && env.GH_HOST !== 'github.com') o['github.apiUrl'] = `https://${env.GH_HOST}/api/v3`;
  const defaults = defaultSettings() as unknown as Json;
  const set = (key: string, name: string, sample: unknown) => {
    const raw = env[name];
    if (raw === undefined || raw === '') return;
    o[key] = parseEnvValue(name, raw, sample);
  };
  for (const [alias, key] of Object.entries(ENV_ALIASES)) set(key, `DIFF_LEPPARD_${alias}`, defaults[key]);
  for (const [k, sample] of Object.entries(defaults)) {
    if (NESTED.includes(k)) {
      for (const [g, gs] of Object.entries(sample as Json)) set(`${k}.${g}`, `DIFF_LEPPARD_${upperSnake(k)}_${upperSnake(g)}`, gs);
    } else set(k, `DIFF_LEPPARD_${upperSnake(k)}`, sample);
  }
  return o;
}

function validate(s: CliSettings): void {
  const int = (k: keyof CliSettings, min: number, max = Number.MAX_SAFE_INTEGER) => {
    const v = s[k] as unknown;
    if (typeof v !== 'number' || !Number.isInteger(v) || v < min || v > max) {
      throw new Error(`${k} must be a whole number between ${min} and ${max === Number.MAX_SAFE_INTEGER ? '∞' : max} (got ${JSON.stringify(v)})`);
    }
  };
  const oneOf = (name: string, v: unknown, allowed: readonly string[]) => {
    if (!allowed.includes(v as string)) throw new Error(`${name} must be one of ${allowed.join(', ')} (got ${JSON.stringify(v)})`);
  };
  const bool = (name: string, v: unknown) => {
    if (typeof v !== 'boolean') throw new Error(`${name} must be true or false (got ${JSON.stringify(v)})`);
  };
  oneOf('provider', s.provider, ['openai', 'ollama']);
  oneOf('jsonMode', s.jsonMode, ['json_object', 'json_schema', 'none']);
  oneOf('minimumSeverity', s.minimumSeverity, SEVERITIES);
  oneOf('github.reviewEvent', s.github.reviewEvent, ['COMMENT', 'REQUEST_CHANGES_IF_BLOCKING', 'PENDING']);
  int('maxChunkChars', 0);
  if (s.maxChunkChars > 0 && s.maxChunkChars < 1000) throw new Error(`maxChunkChars must be 0 (auto) or at least 1000 (got ${s.maxChunkChars})`);
  int('concurrency', 1, 64);
  int('maxOutputTokens', 16);
  int('requestTimeoutSeconds', 1);
  int('contextLines', 0, 1000);
  int('ollamaNumCtx', 256);
  if (typeof s.temperature !== 'number' || !(s.temperature >= 0 && s.temperature <= 2)) {
    throw new Error(`temperature must be a number between 0 and 2 (got ${JSON.stringify(s.temperature)})`);
  }
  bool('stream', s.stream);
  bool('includeUntracked', s.includeUntracked);
  bool('github.suggestionBlocks', s.github.suggestionBlocks);
  bool('github.attribution', s.github.attribution);
  const w = s.watch;
  oneOf('watch.event', w.event, ['COMMENT', 'REQUEST_CHANGES_IF_BLOCKING', 'PENDING']);
  oneOf('watch.reviewRequests', w.reviewRequests, ['user', 'team', 'off']);
  for (const [k, v] of [['watch.ownPullRequests', w.ownPullRequests], ['watch.rereviewOnPush', w.rereviewOnPush], ['watch.skipDrafts', w.skipDrafts]] as const) bool(k, v);
  if (typeof w.intervalMinutes !== 'number' || !(w.intervalMinutes >= 1)) throw new Error(`watch.intervalMinutes must be at least 1 (got ${JSON.stringify(w.intervalMinutes)})`);
  if (!Number.isInteger(w.maxPerRun) || w.maxPerRun < 1) throw new Error(`watch.maxPerRun must be a whole number ≥ 1 (got ${JSON.stringify(w.maxPerRun)})`);
  for (const [k, v] of [['watch.repos', w.repos], ['watch.excludeRepos', w.excludeRepos]] as const) {
    if (!Array.isArray(v) || v.some((r) => typeof r !== 'string' || !/^[\w.-]+\/([\w.-]+|\*)$/.test(r))) throw new Error(`${k} must be a list of "owner/repo" or "owner/*"`);
  }
  if (typeof w.query !== 'string' || typeof w.stateFile !== 'string') throw new Error('watch.query and watch.stateFile must be strings');
  for (const [k, v] of [['baseUrl', s.baseUrl], ['github.apiUrl', s.github.apiUrl]] as const) {
    try {
      const u = new URL(v);
      if (u.protocol !== 'http:' && u.protocol !== 'https:') throw new Error();
    } catch {
      throw new Error(`${k} must be an http(s) URL (got ${JSON.stringify(v)})`);
    }
  }
  if (!Array.isArray(s.excludeGlobs) || s.excludeGlobs.some((g) => typeof g !== 'string')) throw new Error('excludeGlobs must be a list of strings');
  for (const [k, v] of [['extraHeaders', s.extraHeaders], ['extraBody', s.extraBody]] as const) {
    if (!isObj(v)) throw new Error(`${k} must be an object`);
  }
  if (Object.values(s.extraHeaders).some((v) => typeof v !== 'string')) throw new Error('extraHeaders values must be strings');
}

export interface RepoConfigInput {
  json: Json;
  source: string;
}

export interface LoadedConfig {
  settings: CliSettings;
  sources: string[];
  /** Human-readable notes, e.g. repo-config keys that were ignored. */
  warnings: string[];
}

/** Read <root>/.diff-leppard.json if present. */
export async function readRepoConfig(root: string | undefined): Promise<RepoConfigInput | undefined> {
  if (!root) return undefined;
  const file = path.join(root, REPO_CONFIG_FILE);
  const json = await readJsonFile(file);
  return json ? { json, source: file } : undefined;
}

export async function loadConfig(repo: RepoConfigInput | undefined, flags: Json, env = process.env): Promise<LoadedConfig> {
  let settings = defaultSettings() as unknown as Json;
  const sources: string[] = [];
  const warnings: string[] = [];
  const userFile = userConfigPath(env);
  const user = await readJsonFile(userFile);
  if (user) {
    settings = merge(settings, user);
    sources.push(userFile);
  }
  if (repo) {
    const { allowed, ignored } = filterRepoConfig(repo.json);
    if (ignored.length) {
      warnings.push(
        `${repo.source}: ignoring ${ignored.join(', ')}. Repo config may only set ${REPO_CONFIG_KEYS.join(', ')}; ` +
          `put server, credential and GitHub settings in ${userFile} or DIFF_LEPPARD_* variables.`,
      );
    }
    settings = merge(settings, allowed);
    sources.push(repo.source);
  }
  settings = merge(settings, envSettings(env));
  settings = merge(settings, flags);
  const s = settings as unknown as CliSettings;
  validate(s);
  return { settings: s, sources, warnings };
}
